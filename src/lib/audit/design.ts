import type { Page } from "playwright-core";
import type { CheckResult } from "./types";

/**
 * Visual design checks, measured in the rendered page rather than read from code: leftover template content,
 * broken and stretched images, overlapping or cut-off text, unreadably small text on phones, very long lines,
 * a pile of fonts, and missing keyboard focus indicators.
 */

export interface DesignFacts {
  title: string;
  placeholders: string[];
  brokenImages: string[];
  distorted: string[];
  overlaps: string[];
  clipped: string[];
  longLines: string[];
  fonts: { family: string; share: number }[];
}

/** Runs in the page (desktop pass). Self-contained: it is serialized into the browser. */
export function designAudit(): DesignFacts {
  const describe = (el: Element) => {
    const cls = (el.getAttribute("class") || "").trim().split(/\s+/).filter(Boolean).slice(0, 2);
    return el.tagName.toLowerCase() + (el.id ? `#${el.id}` : "") + (cls.length ? "." + cls.join(".") : "");
  };
  const visible = (el: Element) => {
    const st = getComputedStyle(el);
    if (st.display === "none" || st.visibility !== "visible" || Number(st.opacity) < 0.1) return false;
    const r = el.getBoundingClientRect();
    return r.width > 1 && r.height > 1;
  };
  const clip = (s: string, n = 60) => (s.length > n ? s.slice(0, n) + "…" : s);

  // ---- Leftover template and placeholder content ----
  const placeholders: string[] = [];
  const title = document.title.trim();
  const DEFAULT_TITLES = ["Create Next App", "Vite + React", "Vite + React + TS", "Vite + Vue", "Vite + Svelte", "Vite App", "React App", "Document", "v0 App", "Lovable App", "Lovable Generated Project", "My App", "Untitled"];
  if (DEFAULT_TITLES.some((t) => t.toLowerCase() === title.toLowerCase())) placeholders.push(`page title is the template default "${title}"`);
  const desc = document.querySelector('meta[name="description" i]')?.getAttribute("content") ?? "";
  if (/^Generated by create next app$|^Web site created using create-react-app$/i.test(desc.trim())) placeholders.push(`meta description is the template default "${desc.trim()}"`);
  const STARTER = [/lorem ipsum/i, /get started by editing/i, /edit <?code>?\s*src\/(app|App)\.[jt]sx?/i, /click on the (vite|react|vue|svelte) (and \w+ )?logos? to learn more/i, /save and see your changes instantly/i, /\[object Object\]/];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  let seenText = 0;
  while ((node = walker.nextNode()) && seenText < 5000) {
    const text = (node.textContent || "").trim();
    if (!text) continue;
    const parent = node.parentElement;
    if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT", "CODE", "PRE", "TEXTAREA", "KBD", "SAMP"].includes(parent.tagName) || !visible(parent)) continue;
    seenText++;
    const hit = STARTER.find((re) => re.test(text));
    // Values a broken render prints: a text node that is exactly undefined / NaN / null, or "$NaN"-style output.
    const broken = /^(undefined|NaN|null)$/.test(text) || /(^|\s|\$|₹|€|£)NaN(\s|%|$)/.test(text) || /\{\{\s*[\w.]+\s*\}\}/.test(text);
    if (hit || broken) placeholders.push(`${describe(parent)}: "${clip(text)}"`);
    if (placeholders.length >= 10) break;
  }
  const TEMPLATE_ASSETS = /\/(next|vite|react|vercel|file|globe|window)\.svg($|\?)/;
  const imgs = Array.from(document.images);
  const templateImgs = imgs.filter((i) => TEMPLATE_ASSETS.test(i.currentSrc || i.src) && visible(i));
  // next.svg + vercel.svg together, or vite.svg / react.svg, is the starter page's logo row.
  const names = new Set(templateImgs.map((i) => (i.currentSrc || i.src).match(TEMPLATE_ASSETS)![1]));
  if ((names.has("next") && names.has("vercel")) || names.has("vite") || names.has("react")) {
    placeholders.push(`starter-template logos on the page: ${[...names].map((n) => n + ".svg").join(", ")}`);
  }

  // ---- Images ----
  const brokenImages: string[] = [];
  const distorted: string[] = [];
  const near = window.innerHeight * 2; // lazy images further down may not have loaded yet
  for (const img of imgs) {
    if (!visible(img)) continue;
    const r = img.getBoundingClientRect();
    const src = (img.currentSrc || img.src || "").split("?")[0];
    if (img.complete && img.naturalWidth === 0 && src && !src.startsWith("data:") && r.top < near) {
      let shown = src;
      try {
        const u = new URL(src);
        shown = u.origin === location.origin ? u.pathname : u.host + u.pathname;
      } catch {}
      brokenImages.push(`${describe(img)} ${clip(shown, 70)}`);
      continue;
    }
    if (!img.naturalWidth || !img.naturalHeight || r.width < 40 || r.height < 40 || /\.svg$/i.test(src)) continue;
    const fit = getComputedStyle(img).objectFit;
    if (fit !== "fill") continue; // cover / contain / scale-down keep proportions
    const natural = img.naturalWidth / img.naturalHeight;
    const shown = r.width / r.height;
    const off = Math.abs(shown / natural - 1);
    if (off > 0.1) distorted.push(`${describe(img)} shown ${Math.round(r.width)}×${Math.round(r.height)} but the image is ${img.naturalWidth}×${img.naturalHeight} (${Math.round(off * 100)}% ${shown > natural ? "wider" : "taller"})`);
  }

  // ---- Text boxes (elements with their own visible text) ----
  type Box = { el: Element; r: DOMRect };
  // The rectangles of the element's own lines of text, not its box: a paragraph's box runs under floats and
  // padding its text never reaches.
  const lineRects = (el: Element): DOMRect[] => {
    const out: DOMRect[] = [];
    for (const n of Array.from(el.childNodes)) {
      if (n.nodeType !== 3 || !(n.textContent || "").trim()) continue;
      const range = document.createRange();
      range.selectNodeContents(n);
      for (const r of Array.from(range.getClientRects())) if (r.width > 2 && r.height > 2) out.push(r);
    }
    return out;
  };
  const boxes: Box[] = [];
  for (const el of Array.from(document.body.querySelectorAll("*"))) {
    if (boxes.length >= 600) break;
    const own = Array.from(el.childNodes).some((n) => n.nodeType === 3 && (n.textContent || "").trim().length > 1);
    if (!own || ["SCRIPT", "STYLE", "NOSCRIPT", "OPTION"].includes(el.tagName) || !visible(el)) continue;
    const r = el.getBoundingClientRect();
    if (r.bottom < 0 || r.top > document.documentElement.scrollHeight) continue;
    boxes.push({ el, r });
  }

  // Overlapping text: two unrelated text boxes on top of each other where the overlap is actually visible
  // (the topmost element at that point is one of the two, and the lower one isn't clipped away by an ancestor).
  const overlaps: string[] = [];
  const clippedAway = (el: Element, x: number, y: number) => {
    for (let p = el.parentElement; p && p !== document.body; p = p.parentElement) {
      const st = getComputedStyle(p);
      if (st.overflow !== "visible" || st.overflowX !== "visible" || st.overflowY !== "visible") {
        const pr = p.getBoundingClientRect();
        if (x < pr.left || x > pr.right || y < pr.top || y > pr.bottom) return true;
      }
    }
    return false;
  };
  // A rotated or skewed ancestor inflates bounding boxes beyond the drawn text, so those can't be compared.
  const transformed = (el: Element) => {
    for (let p: Element | null = el; p && p !== document.body; p = p.parentElement) {
      const t = getComputedStyle(p).transform;
      const m = t && t !== "none" ? t.match(/matrix\(([^)]+)\)/) : null;
      if (t && t !== "none" && (!m || m[1].split(",").slice(1, 3).some((v) => Math.abs(parseFloat(v)) > 0.001))) return true;
    }
    return false;
  };
  const inView = boxes.filter((b) => b.r.top < window.innerHeight * 1.5 && b.r.bottom > 0 && !transformed(b.el));
  const lines = inView.map((b) => ({ ...b, lines: lineRects(b.el) }));
  outer: for (let i = 0; i < lines.length && overlaps.length < 6; i++) {
    for (let j = i + 1; j < lines.length && overlaps.length < 6; j++) {
      const a = lines[i];
      const b = lines[j];
      if (a.el.contains(b.el) || b.el.contains(a.el)) continue;
      // The same text stacked on itself is a deliberate effect (gradient or glow layers), not a broken layout.
      if ((a.el.textContent || "").trim() === (b.el.textContent || "").trim()) continue;
      const pos = (el: Element) => getComputedStyle(el).position;
      if (pos(a.el) === "fixed" || pos(b.el) === "fixed") continue;
      for (const ra of a.lines) {
        for (const rb of b.lines) {
          const w = Math.min(ra.right, rb.right) - Math.max(ra.left, rb.left);
          const h = Math.min(ra.bottom, rb.bottom) - Math.max(ra.top, rb.top);
          if (w <= 4 || h <= 4) continue;
          if ((w * h) / Math.min(ra.width * ra.height, rb.width * rb.height) < 0.3) continue;
          const x = Math.max(ra.left, rb.left) + w / 2;
          const y = Math.max(ra.top, rb.top) + h / 2;
          if (clippedAway(a.el, x, y) || clippedAway(b.el, x, y)) continue;
          const top = document.elementFromPoint(x, y);
          if (!top || !(a.el.contains(top) || b.el.contains(top) || top.contains(a.el) || top.contains(b.el))) continue;
          overlaps.push(`"${clip((a.el.textContent || "").trim(), 30)}" (${describe(a.el)}) overlaps "${clip((b.el.textContent || "").trim(), 30)}" (${describe(b.el)})`);
          continue outer;
        }
      }
    }
  }

  // Cut-off text: the element's own text is clipped by its box, without an intentional ellipsis or line clamp.
  const clipped: string[] = [];
  for (const { el } of boxes) {
    if (clipped.length >= 6) break;
    if (["INPUT", "TEXTAREA", "SELECT", "BUTTON"].includes(el.tagName) || el.children.length > 0) continue;
    const st = getComputedStyle(el);
    const hidesX = st.overflowX === "hidden" || st.overflowX === "clip";
    const hidesY = st.overflowY === "hidden" || st.overflowY === "clip";
    const e = el as HTMLElement;
    const cutX = hidesX && e.scrollWidth > e.clientWidth + 2 && st.textOverflow !== "ellipsis";
    const cutY = hidesY && e.scrollHeight > e.clientHeight + 4 && st.getPropertyValue("-webkit-line-clamp") === "none";
    if ((cutX || cutY) && e.clientWidth > 0 && e.clientHeight > 0) clipped.push(`${describe(el)} "${clip((el.textContent || "").trim(), 40)}" shows ${e.clientWidth}×${e.clientHeight} of ${e.scrollWidth}×${e.scrollHeight}px`);
  }

  // Very long lines in running text (estimated from width and font size; ~0.5em per character).
  const longLines: string[] = [];
  for (const { el, r } of boxes) {
    if (longLines.length >= 5) break;
    if (!["P", "LI", "DD", "BLOCKQUOTE", "TD"].includes(el.tagName)) continue;
    const text = (el.textContent || "").trim();
    if (text.length < 240) continue;
    const size = parseFloat(getComputedStyle(el).fontSize) || 16;
    const perLine = Math.round(r.width / (size * 0.5));
    if (perLine > 110) longLines.push(`${describe(el)} about ${perLine} characters per line ("${clip(text, 40)}")`);
  }

  // Fonts, weighted by how much visible text uses each; icon fonts aren't typography.
  const weight = new Map<string, number>();
  let total = 0;
  for (const { el } of boxes) {
    const fam = getComputedStyle(el).fontFamily.split(",")[0].replace(/["']/g, "").trim();
    if (!fam || /icon|awesome|symbol|emoji/i.test(fam)) continue;
    const n = Array.from(el.childNodes).reduce((s, c) => s + (c.nodeType === 3 ? (c.textContent || "").trim().length : 0), 0);
    weight.set(fam, (weight.get(fam) ?? 0) + n);
    total += n;
  }
  const fonts = [...weight].map(([family, n]) => ({ family, share: total ? n / total : 0 })).filter((f) => f.share >= 0.02).sort((a, b) => b.share - a.share);

  return { title, placeholders, brokenImages, distorted, overlaps, clipped, longLines, fonts };
}

/**
 * Runs in the page (390px phone pass). Like Lighthouse's legible-font-size audit, it measures the share of
 * visible text characters set below 12px. Text hidden from assistive tech (decorative illustrations) is skipped.
 */
export function phoneTextAudit(): { small: string[]; smallChars: number; totalChars: number } {
  const found: { label: string; chars: number }[] = [];
  let smallChars = 0;
  let totalChars = 0;
  for (const el of Array.from(document.body.querySelectorAll("*"))) {
    const text = Array.from(el.childNodes).reduce((s, c) => s + (c.nodeType === 3 ? (c.textContent || "").trim() : ""), "");
    if (text.length < 2 || ["SCRIPT", "STYLE", "NOSCRIPT", "OPTION"].includes(el.tagName) || el.closest("[aria-hidden='true'], svg")) continue;
    const st = getComputedStyle(el);
    if (st.display === "none" || st.visibility !== "visible" || Number(st.opacity) < 0.1) continue;
    const r = el.getBoundingClientRect();
    if (r.width <= 1 || r.height <= 1) continue;
    totalChars += text.length;
    const size = parseFloat(st.fontSize);
    if (size < 12) {
      smallChars += text.length;
      const cls = (el.getAttribute("class") || "").trim().split(/\s+/).filter(Boolean).slice(0, 2);
      found.push({ label: `${el.tagName.toLowerCase()}${cls.length ? "." + cls.join(".") : ""} ${Math.round(size * 10) / 10}px "${text.slice(0, 40)}"`, chars: text.length });
    }
  }
  found.sort((a, b) => b.chars - a.chars);
  return { small: found.map((f) => f.label), smallChars, totalChars };
}

/**
 * Keyboard focus visibility (WCAG 2.4.7), judged on pixels: for each of the first visible links and controls,
 * the area around it is captured unfocused and then focused from the keyboard (after a Tab press, so
 * :focus-visible styles apply), with transitions finished and the text caret hidden. Identical pixels mean a
 * keyboard user sees no sign of where they are, however the focus style would have been drawn.
 */
export async function focusAudit(page: Page, limit = 12): Promise<{ checked: number; missing: string[] } | null> {
  try {
    await page.keyboard.press("Tab");
    const SEL = "a[href], button:not([disabled]), input:not([type=hidden]):not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex='-1'])";
    const handles = await page.$$(SEL);
    const viewport = page.viewportSize() ?? { width: 1280, height: 800 };
    let checked = 0;
    const missing: string[] = [];
    for (const h of handles) {
      if (checked >= limit) break;
      const info = await h.evaluate((el, screens) => {
        const st = getComputedStyle(el);
        const r = el.getBoundingClientRect();
        const docTop = r.top + window.scrollY;
        if (st.visibility !== "visible" || st.display === "none" || r.width <= 1 || r.height <= 1 || docTop > window.innerHeight * screens) return null;
        const cls = (el.getAttribute("class") || "").trim().split(/\s+/).filter(Boolean).slice(0, 2);
        return `${el.tagName.toLowerCase()}${cls.length ? "." + cls.join(".") : ""} "${(el.textContent || el.getAttribute("aria-label") || el.getAttribute("placeholder") || "").trim().slice(0, 30)}"`;
      }, 3);
      if (!info) continue;
      await h.evaluate((el) => {
        (el as HTMLElement).blur();
        el.scrollIntoView({ block: "center" });
      });
      const box = await h.boundingBox();
      if (!box || box.width < 2 || box.height < 2) continue;
      const pad = 8;
      const x = Math.max(0, box.x - pad);
      const y = Math.max(0, box.y - pad);
      const clip = { x, y, width: Math.min(viewport.width - x, box.width + pad * 2), height: Math.min(viewport.height - y, box.height + pad * 2) };
      if (clip.width < 4 || clip.height < 4) continue;
      const shot = () => page.screenshot({ clip, animations: "disabled", caret: "hide", timeout: 3000 });
      const before = await shot();
      const focused = await h.evaluate((el) => {
        (el as HTMLElement).focus({ preventScroll: true });
        return document.activeElement === el;
      });
      if (!focused) continue;
      const after = await shot();
      await h.evaluate((el) => (el as HTMLElement).blur());
      checked++;
      if (before.equals(after)) missing.push(info);
    }
    await page.evaluate(() => window.scrollTo(0, 0));
    return { checked, missing };
  } catch {
    return null;
  }
}

const base = { category: "design", method: "browser" } as const;
const ev = (items: string[], max = 8) => (items.length ? items.slice(0, max).concat(items.length > max ? [`…and ${items.length - max} more`] : []) : undefined);

export function designChecks(d: DesignFacts | null, phone: { small: string[]; smallChars: number; totalChars: number } | null, focus: { checked: number; missing: string[] } | null): CheckResult[] {
  const out: CheckResult[] = [];
  const notMeasured = (id: string, title: string, severity: CheckResult["severity"], category: CheckResult["category"] = "design"): CheckResult => ({
    ...base,
    category,
    id,
    title,
    severity,
    status: "skip",
    detail: "Not measured: the page kept the browser busy, so this couldn't be read in time.",
  });
  if (!d) {
    out.push(
      notMeasured("ux-placeholder", "No leftover template or placeholder content", "medium"),
      notMeasured("ux-images", "Images load and keep their proportions", "medium"),
      notMeasured("ux-overlap", "No overlapping text", "medium"),
      notMeasured("ux-clipped", "No cut-off text", "low"),
      notMeasured("ux-line-length", "Comfortable line length", "low"),
      notMeasured("ux-fonts", "Consistent typography", "low")
    );
  } else {
    out.push({
      ...base,
      id: "ux-placeholder",
      severity: "medium",
      title: "No leftover template or placeholder content",
      status: d.placeholders.length ? "fail" : "pass",
      detail: d.placeholders.length
        ? "Visitors can see starter-template or placeholder content, or values a broken render prints (undefined, NaN, [object Object]). It reads as unfinished."
        : "No template titles, starter text, lorem ipsum, template logos or broken values (undefined, NaN, [object Object]) on the page.",
      evidence: ev(d.placeholders),
      fix: d.placeholders.length ? "Replace the template title, description and starter content with your own, and check the components that print undefined or NaN for missing data." : undefined,
    });
    const imageProblems = d.brokenImages.length + d.distorted.length;
    out.push({
      ...base,
      id: "ux-images",
      severity: "medium",
      title: "Images load and keep their proportions",
      status: d.brokenImages.length ? "fail" : d.distorted.length ? "warn" : "pass",
      detail: imageProblems
        ? `${d.brokenImages.length} image(s) failed to load (visitors see a broken-image icon or empty box) and ${d.distorted.length} are stretched or squashed out of their natural proportions.`
        : "Every visible image on the first screens loaded and is shown in its natural proportions.",
      evidence: ev([...d.brokenImages.map((s) => `broken: ${s}`), ...d.distorted.map((s) => `stretched: ${s}`)]),
      fix: imageProblems ? "Fix the image paths; for stretched images set width and height in the image's own ratio, or use object-fit: cover." : undefined,
    });
    out.push({
      ...base,
      id: "ux-overlap",
      severity: "medium",
      title: "No overlapping text",
      status: d.overlaps.length ? "fail" : "pass",
      detail: d.overlaps.length
        ? `${d.overlaps.length} place(s) on the first screens where text is drawn on top of other text, which usually means a broken layout at this width.`
        : "No visible text sits on top of other text on the first screens of the 1280px layout.",
      evidence: ev(d.overlaps),
      fix: d.overlaps.length ? "Look for absolute positioning, negative margins or fixed heights around these elements." : undefined,
    });
    out.push({
      ...base,
      id: "ux-clipped",
      severity: "low",
      title: "No cut-off text",
      status: d.clipped.length ? "warn" : "pass",
      detail: d.clipped.length
        ? `${d.clipped.length} element(s) hide part of their text behind overflow: hidden, without an ellipsis to show it was shortened.`
        : "No text is silently cut off by its container.",
      evidence: ev(d.clipped),
      fix: d.clipped.length ? "Let the box grow with its text, or shorten deliberately with text-overflow: ellipsis or line-clamp so readers can tell." : undefined,
    });
    out.push({
      ...base,
      id: "ux-line-length",
      severity: "low",
      title: "Comfortable line length",
      status: d.longLines.length ? "warn" : "pass",
      detail: d.longLines.length
        ? "Some paragraphs run well past 100 characters per line at desktop width, which makes them tiring to read (around 50–80 is comfortable)."
        : "Running text stays under about 110 characters per line at desktop width.",
      evidence: ev(d.longLines),
      fix: d.longLines.length ? "Cap the text column, for example max-width: 70ch." : undefined,
    });
    out.push({
      ...base,
      id: "ux-fonts",
      severity: "low",
      title: "Consistent typography",
      status: d.fonts.length > 3 ? "warn" : "pass",
      detail:
        d.fonts.length > 3
          ? `${d.fonts.length} different typefaces each set at least 2% of the visible text; more than three usually looks unplanned.`
          : `${d.fonts.length || 1} typeface${d.fonts.length === 1 ? "" : "s"} carry the visible text.`,
      evidence: d.fonts.map((f) => `${f.family}: ${Math.round(f.share * 100)}% of text`),
      fix: d.fonts.length > 3 ? "Pick one typeface for text and at most one for headings or code." : undefined,
    });
  }
  if (!phone) out.push(notMeasured("ux-text-size", "Readable text size on phones", "medium"));
  else {
    const share = phone.totalChars ? phone.smallChars / phone.totalChars : 0;
    const pct = Math.round(share * 100);
    out.push({
      ...base,
      id: "ux-text-size",
      severity: "medium",
      title: "Readable text size on phones",
      status: share > 0.4 ? "fail" : share > 0.1 ? "warn" : "pass",
      detail:
        share > 0.1
          ? `${pct}% of the visible text on the 390px layout is set below 12px, too small to read without zooming${share > 0.4 ? " (Lighthouse fails a page above 40%)" : ""}.`
          : phone.smallChars
            ? `${pct === 0 ? "Under 1" : pct}% of the visible text on the 390px layout is below 12px (small labels); the rest is readable.`
            : "All visible text on the 390px layout is at least 12px.",
      evidence: share > 0.1 ? ev(phone.small) : undefined,
      fix: share > 0.1 ? "Use at least 16px for body text and 12px for labels and small print on phones." : undefined,
    });
  }
  if (!focus) out.push(notMeasured("a11y-focus-visible", "Keyboard focus is visible (WCAG 2.4.7)", "medium", "accessibility"));
  else if (focus.checked === 0) {
    out.push({ ...base, category: "accessibility", id: "a11y-focus-visible", severity: "medium", title: "Keyboard focus is visible (WCAG 2.4.7)", status: "skip", detail: "The page has no focusable links or controls on its first screens." });
  } else {
    const share = focus.missing.length / focus.checked;
    out.push({
      ...base,
      category: "accessibility",
      id: "a11y-focus-visible",
      severity: "medium",
      title: "Keyboard focus is visible (WCAG 2.4.7)",
      status: !focus.missing.length ? "pass" : share > 0.3 ? "fail" : "warn",
      detail: focus.missing.length
        ? `${focus.missing.length} of ${focus.checked} links and controls look pixel-for-pixel the same when focused with the keyboard, so keyboard users can't see where they are.`
        : `All ${focus.checked} links and controls checked visibly change when focused with the keyboard (compared pixel by pixel).`,
      evidence: ev(focus.missing),
      fix: focus.missing.length ? "Don't remove the outline without a replacement: style :focus-visible with an outline or ring that contrasts with the background." : undefined,
    });
  }
  return out;
}
