import { combinedHeaderFix } from "./hosting";
import { CATEGORY_LABEL, computeScore, METHOD_LABEL, SEVERITY_WEIGHT, type AuditMeta, type Category, type CheckResult } from "./types";

/** Failures and warnings ordered by how much they cost the score. */
export function topPriorities(checks: CheckResult[], limit = 5): CheckResult[] {
  const impact = (c: CheckResult) => SEVERITY_WEIGHT[c.severity] * (c.status === "fail" ? 1 : 0.5);
  return checks.filter((c) => c.status === "fail" || c.status === "warn").sort((a, b) => impact(b) - impact(a)).slice(0, limit);
}

export interface ReportAudit {
  id: string;
  label: string;
  target: string;
  finalUrl: string | null;
  source: string;
  createdAt: Date;
  durationMs: number | null;
  checks: CheckResult[];
  meta: AuditMeta;
}

const STATUS_WORD = { fail: "Failed", warn: "Warning", pass: "Passed", skip: "Not run" } as const;
const md = (s: string) => s.replace(/([\\`*_[\]<>|])/g, "\\$1");

/** A report that pastes cleanly into a GitHub issue or pull request. */
export function toMarkdown(a: ReportAudit, reportUrl: string): string {
  const score = computeScore(a.checks);
  const site = a.meta.github ? `${a.meta.github.repo} @ ${a.meta.github.ref}` : a.finalUrl ?? a.target;
  const lines: string[] = [
    `# VibeCheck audit: ${md(a.label)}`,
    "",
    `**Score ${score.score ?? "n/a"}/100**${score.capped ? " (capped: a critical check failed)" : ""} · ${score.counts.fail} failed, ${score.counts.warn} warnings, ${score.counts.pass} passed${score.counts.skip ? `, ${score.counts.skip} not run` : ""}`,
    "",
    `- Audited: ${md(site)}`,
    `- When: ${a.createdAt.toISOString().replace("T", " ").slice(0, 16)} UTC${a.durationMs ? `, took ${Math.round(a.durationMs / 1000)}s` : ""}`,
    `- Full report with evidence: ${reportUrl}`,
    "",
  ];
  const top = topPriorities(a.checks);
  if (top.length) {
    lines.push("## Fix these first", "");
    top.forEach((c, i) => lines.push(`${i + 1}. **${md(c.title)}** (${c.severity}): ${md(c.detail)}${c.fix ? `\n   - Fix: ${md(c.fix)}` : ""}`));
    lines.push("");
  }
  const block = combinedHeaderFix(a.checks, a.meta.host?.id);
  if (block) {
    lines.push("## Fix the security headers in one go", "", `Hosted on ${a.meta.host!.name}. Put this in ${block.title}:`, "", "```", block.code, "```", ...(block.note ? ["", block.note] : []), "");
  }
  for (const cat of Object.keys(CATEGORY_LABEL) as Category[]) {
    const list = a.checks.filter((c) => c.category === cat);
    if (!list.length) continue;
    const problems = list.filter((c) => c.status === "fail" || c.status === "warn");
    lines.push(`## ${CATEGORY_LABEL[cat]} (${list.filter((c) => c.status === "pass").length}/${list.filter((c) => c.status !== "skip").length} passed)`, "");
    for (const c of problems) {
      lines.push(`- [ ] **${STATUS_WORD[c.status]}: ${md(c.title)}** (${c.severity}, ${METHOD_LABEL[c.method]}). ${md(c.detail)}`);
      for (const e of (c.evidence ?? []).slice(0, 6)) lines.push(`  - \`${e.replace(/`/g, "'")}\``);
      if (c.fix) lines.push(`  - Fix: ${md(c.fix)}`);
    }
    const passed = list.filter((c) => c.status === "pass").map((c) => md(c.title));
    if (passed.length) lines.push(`- Passed: ${passed.join(", ")}`);
    const skipped = list.filter((c) => c.status === "skip").map((c) => md(c.title));
    if (skipped.length) lines.push(`- Not run: ${skipped.join(", ")}`);
    lines.push("");
  }
  lines.push("---", `Generated by VibeCheck. Every check and its thresholds: ${new URL("/methodology", reportUrl).toString()}`);
  return lines.join("\n");
}

/** Machine-readable report: the same checks and evidence the page shows. */
export function toJson(a: ReportAudit, reportUrl: string) {
  const score = computeScore(a.checks);
  return {
    id: a.id,
    url: reportUrl,
    label: a.label,
    source: a.source,
    target: a.target,
    finalUrl: a.finalUrl,
    createdAt: a.createdAt.toISOString(),
    durationMs: a.durationMs,
    score: score.score,
    capped: score.capped,
    counts: score.counts,
    checks: a.checks,
    meta: { title: a.meta.title, statusCode: a.meta.statusCode, browser: a.meta.browser, build: a.meta.build, github: a.meta.github, crawl: a.meta.crawl },
  };
}
